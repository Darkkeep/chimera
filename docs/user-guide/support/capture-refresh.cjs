const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const fixtureDir = process.env.CHIMERA_GUIDE_DIR || path.resolve('workspace/user-guide-20261014');
  const fixture = JSON.parse(await fs.readFile(path.join(fixtureDir, 'fixture.json')));
  const images = path.resolve('docs/user-guide/images');
  const browser = await chromium.launch();
  const page = await browser.newPage({ baseURL: process.env.GUIDE_URL || 'http://127.0.0.1:5179', viewport: { width: 1500, height: 1400 }, colorScheme: 'light' });
  const captures = [];
  try {
    await page.route('**/api/ai-connection', route => route.fulfill({ json: { configured: true, textModel: 'Documentation fixture', canManage: true } }));
    await page.route('**/content-draft', route => route.abort());
    await page.route('**/content-drafts/course', route => route.abort());
    await page.goto('/');
    const projects = await (await page.request.get('/api/projects')).json();
    if (projects.length !== 1 || projects[0].id !== fixture.projectId) throw new Error('Requires the isolated documentation fixture.');
    const previous = await (await page.request.get(`/api/projects/${fixture.projectId}`)).json();
    for (const group of previous.storyboard.assessments.filter(group => group.title === 'Documentation knowledge check')) {
      const latest = await (await page.request.get(`/api/projects/${fixture.projectId}`)).json();
      const removed = await page.request.delete(`/api/projects/${fixture.projectId}/assessments/${group.id}`, { headers: { 'If-Match': `"${latest.storyboard.revision}"` } });
      if (!removed.ok()) throw new Error('Could not reset the demonstration Assessment.');
    }
    await page.reload();
    const button = name => page.getByRole('button', { name, exact: true });
    async function shot(name, locator) {
      await expect(locator.first()).toBeVisible();
      await locator.first().screenshot({ path: path.join(images, name + '.png') });
      captures.push({ file: name + '.png' });
      console.log(name);
    }
    await shot('my-work-current', page.getByRole('region', { name: 'My Work', exact: true }));
    await button('Resume authoring').click();
    await shot('workspace', page.locator('.app-shell'));
    await shot('top-actions', page.locator('.top-actions'));
    await shot('scene-sequence', page.locator('.scene-list'));
    await button('Create project').click();
    await shot('create-project', page.getByRole('dialog', { name: 'Name your course', exact: true }));
    await button('Close new project').click();
    await button('Edit scene').click();
    let editor = page.getByRole('dialog').last();
    await editor.getByRole('tab', { name: 'Details', exact: true }).click();
    await editor.getByLabel('Scene prompt').fill('Improve the wording while preserving the learning objectives, title, narration, and required status.');
    await shot('scene-editor', editor);
    await editor.getByRole('combobox', { name: 'Rendering mode', exact: true }).selectOption('template');
    await shot('template-selection', editor);
    await editor.getByRole('combobox', { name: 'Rendering mode', exact: true }).selectOption('native');
    await editor.getByRole('tab', { name: 'Stage', exact: true }).click();
    await shot('scene-canvas-editor', editor);
    await editor.getByRole('button', { name: 'Stagger text entrances', exact: true }).click();
    await editor.getByRole('button', { name: 'Identify the purpose of a storyboard. element', exact: true }).click();
    await shot('animation-inspector', editor);
    await editor.getByRole('button', { name: 'Fit text', exact: true }).click();
    await shot('text-fit', editor);
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
    await button('Add scene').first().click();
    await page.getByRole('combobox', { name: 'Scene type', exact: true }).selectOption('question');
    await shot('new-scene', page.getByRole('dialog').last());
    await button('Close scene editor').click();
    await page.locator('.scene-row').nth(1).click();
    await shot('assessment-launch', page.locator('.assessment-authoring-launch'));
    await button('Edit question').click();
    const question = page.getByRole('dialog').last();
    await question.getByRole('button', { name: 'Save question', exact: true }).click();
    await expect(question.getByText('Saved to', { exact: false })).toBeVisible();
    await shot('assessment-actions', page.locator('.assessment-editor-footer'));
    for (const type of ['single-choice', 'multiple-response', 'true-false', 'ordering', 'drag-drop', 'matching', 'short-answer']) {
      await question.getByLabel('Question type').selectOption(type);
      await shot('question-' + type, question);
    }
    await shot('assessment-rules', page.locator('.assessment-settings'));
    page.once('dialog', dialog => dialog.accept());
    await button('Close question editor').click();
    await button('Edit scene').click();
    editor = page.getByRole('dialog').last();
    await editor.getByRole('tab', { name: 'Stage', exact: true }).click();
    await shot('question-placement', editor);
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
    await button('Review tools').click();
    await shot('review-tools', page.locator('#review-tools'));
    await button('Assessments').click();
    const assessments = page.getByRole('dialog', { name: 'Assessments', exact: true });
    await assessments.getByRole('button', { name: 'Create assessment', exact: true }).click();
    await assessments.getByLabel('Assessment title', { exact: true }).fill('Documentation knowledge check');
    await assessments.getByRole('checkbox', { name: /Knowledge check/ }).check();
    await assessments.getByRole('checkbox', { name: /Final review/ }).check();
    await shot('assessments-editor', assessments);
    await assessments.getByRole('button', { name: 'Save assessment', exact: true }).click();
    await expect(assessments.getByRole('button', { name: 'Edit Documentation knowledge check', exact: true })).toBeVisible();
    await shot('assessments-list', assessments);
    await button('Close assessments').click();
    await button('Preview course').click();
    const preview = page.getByRole('dialog', { name: /course preview$/ });
    await preview.getByRole('button', { name: 'Go to scene 2: Knowledge check', exact: true }).click();
    const current = await (await page.request.get(`/api/projects/${fixture.projectId}`)).json();
    const item = current.storyboard.scenes[1].assessmentItem;
    const wrong = item.choices.find(choice => choice.identifier !== item.correctResponse).text;
    const right = item.choices.find(choice => choice.identifier === item.correctResponse).text;
    await shot('learner-question', preview.locator('.assessment-stage-region'));
    await preview.getByLabel(wrong, { exact: true }).check();
    await preview.getByRole('button', { name: 'Check answer', exact: true }).click();
    await shot('learner-feedback', page.getByRole('dialog', { name: 'Not correct', exact: true }));
    await button('Close feedback').click();
    await shot('learner-retry', preview.locator('.assessment-stage-region'));
    await preview.getByRole('button', { name: 'Try again', exact: true }).click();
    await preview.getByLabel(right, { exact: true }).check();
    await preview.getByRole('button', { name: 'Check answer', exact: true }).click();
    await shot('learner-result', page.getByRole('dialog', { name: 'Correct', exact: true }));
    await button('Close feedback').click();
    await button('Close course preview').click();
    await button('Export', { exact: true }).click();
    await shot('export-dialog', page.getByRole('dialog').last());
    await shot('scorm-export', page.locator('.export-section').filter({ has: page.getByRole('heading', { name: 'Learning management system', exact: true }) }));
    await button('Close export').click();
    await button('Create project').click();
    const create = page.getByRole('dialog', { name: 'Name your course', exact: true });
    await create.getByRole('textbox', { name: 'Course name', exact: true }).fill('Course drafting demonstration');
    await create.getByLabel('Attach course design documents').setInputFiles(path.join(fixtureDir, 'study-guide.txt'));
    await create.getByRole('textbox', { name: 'Course prompt', exact: true }).fill('Create a short lesson on reviewing storyboard scenes before publishing, grounded in the attached guide.');
    await create.getByRole('button', { name: 'Create project', exact: true }).click();
    const draftReview = page.getByRole('dialog', { name: 'Draft course scenes', exact: true });
    await shot('course-draft-prompt', draftReview);
    await page.unroute('**/content-drafts/course');
    await page.route('**/content-drafts/course', route => route.fulfill({ json: { scenes: [{ title: 'Review before publishing', sceneType: 'content', extractedText: ['Review each scene for clarity.', 'Preview and validate the course before publishing.'], actionDescription: 'Review the scene with the learner.', narration: 'Review, preview, and validate before publishing.', notes: 'Documentation fixture; not AI-generated.', required: true }] } }));
    await draftReview.getByRole('button', { name: 'Generate course draft', exact: true }).click();
    await expect(draftReview.getByLabel('Generated scenes for review', { exact: true })).toBeVisible();
    await shot('course-draft-review', draftReview);
    await button('Close course drafting').click();
    const temporaryId = await page.evaluate(() => localStorage.getItem('chimera.activeProjectId'));
    const trashed = await page.request.post(`/api/projects/${temporaryId}/trash`);
    if (!trashed.ok()) throw new Error('Could not archive the temporary drafting demonstration.');
    const baseline = await (await page.request.get(`/api/projects/${fixture.projectId}`)).json();
    const blankResponse = await page.request.post(`/api/projects/${fixture.projectId}/scenes`, { headers: { 'If-Match': `"${baseline.storyboard.revision}"` }, data: { title: 'New question', sceneType: 'question' } });
    if (!blankResponse.ok()) throw new Error('Could not create a blank question demonstration.');
    const withBlank = await blankResponse.json();
    const blankId = withBlank.storyboard.scenes.at(-1).id;
    await page.reload();
    await button('Resume authoring').click();
    await page.getByRole('button', { name: /New question question/ }).click();
    await shot('assessment-create', page.locator('.assessment-authoring-launch'));
    const blankRemoved = await page.request.delete(`/api/projects/${fixture.projectId}/scenes/${blankId}`, { headers: { 'If-Match': `"${withBlank.storyboard.revision}"` } });
    if (!blankRemoved.ok()) throw new Error('Could not remove the temporary blank question demonstration.');
    await fs.writeFile(path.resolve('docs/user-guide/refresh-manifest-2026-10-14.json'), JSON.stringify({ capturedAt: new Date().toISOString(), sourceCommit: '6641162', fixture: 'Fresh isolated demonstration workspace. AI configuration display is an inert fixture; generation endpoints blocked; no provider calls.', viewport: { width: 1500, height: 1400 }, screenshots: captures }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
