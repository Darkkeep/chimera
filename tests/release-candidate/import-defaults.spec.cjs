const {test, expect} = require('@playwright/test');
const {openWorkspaceMenu} = require('../onboarding/helpers.cjs');
test.setTimeout(90000);
for (const surface of ['My Work', 'workspace']) test(`${surface}: file start preserves review and reopen with progressive gates off`, async ({page}) => {
  await page.route('**/api/projects', route => route.request().method() === 'GET' ? route.fulfill({json:[]}) : route.continue());
  const progressiveRequests = [];
  page.on('request', request => {if (request.url().includes('/progressive-jobs')) progressiveRequests.push(request.url());});
  await page.goto('/');
  if (surface === 'workspace') await openWorkspaceMenu(page);
  await page.getByRole('button', {name:surface === 'My Work' ? 'New Project' : 'Create project',exact:true}).click();
  await page.getByRole('dialog', {name:'New Project',exact:true}).getByRole('button', {name:'Start from a file'}).click();
  const dialog = page.getByRole('dialog', {name:'Start Experience from Import'});
  await dialog.getByLabel('Experience import file').setInputFiles('backend/tests/fixtures/production-handoff-v1.json');
  await expect(dialog.getByRole('heading', {name:'Pythia production handoff'})).toBeVisible();
  await dialog.getByRole('button', {name:'Create experience and review scenes'}).click();
  await expect(page.getByRole('heading', {name:'Storyboard suggestions'})).toBeVisible();
  const id = await page.evaluate(() => localStorage.getItem('chimera.activeProjectId'));
  const read = async () => (await (await page.request.get(`/api/projects/${id}`)).json());
  const before = await read();
  expect(before.storyboard.scenes).toHaveLength(0);
  const proposal = page.locator('article.enhancement-proposal').filter({hasText:'Pythia production handoff'});
  await expect(proposal.getByText('pending', {exact:true})).toBeVisible();
  await proposal.getByRole('button', {name:'Accept change'}).click();
  await expect(proposal.getByText('accepted', {exact:true})).toBeVisible();
  const accepted = await read();
  expect(accepted.storyboard.revision).toBe(before.storyboard.revision + 1);
  expect(accepted.storyboard.scenes.map(scene => scene.title)).toEqual(['Leave by a marked exit','Check your understanding']);
  expect(accepted.storyboard.scenes[1].assessmentItem.correctResponse).toBe('exit');
  await page.unroute('**/api/projects');
  await page.goto(`/?project_id=${id}&object_id=${accepted.storyboard.scenes[0].id}`);
  await expect(page.getByRole('heading', {name:'Leave by a marked exit',exact:true})).toBeVisible();
  expect((await read()).storyboard).toEqual(accepted.storyboard);
  expect(progressiveRequests).toEqual([]);
});
