const { test, expect } = require('@playwright/test');

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
  test(`assessment question controls precede the scene preview at ${viewport.width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport);
    await page.route('**/api/projects', route => route.request().method() === 'GET'
      ? route.fulfill({ json: [] }) : route.continue());
    await page.route('**/api/ai-connection', route => route.fulfill({ json: { configured: false } }));
    await page.goto('/');
    await page.getByRole('button', { name: 'Create project', exact: true }).click();
    const projectDialog = page.getByRole('dialog', { name: 'Name your course' });
    await projectDialog.getByRole('textbox', { name: 'Course name' }).fill(`Assessment placement ${viewport.width}`);
    await projectDialog.getByRole('button', { name: 'Create project', exact: true }).click();
    await expect(projectDialog).toHaveCount(0);
    await page.getByRole('button', { name: 'Add scene', exact: true }).first().click();
    const sceneDialog = page.getByRole('dialog');
    await sceneDialog.getByRole('textbox', { name: 'Scene title', exact: true }).fill('Safety knowledge check');
    await sceneDialog.getByRole('combobox', { name: 'Scene type', exact: true }).selectOption('question');
    await sceneDialog.getByRole('button', { name: 'Create scene', exact: true }).click();
    await expect(sceneDialog).toHaveCount(0);

    const selectedScene = page.getByRole('region', { name: 'Selected scene', exact: true });
    const assessment = selectedScene.getByRole('region', { name: 'Scene question', exact: true });
    const createQuestion = assessment.getByRole('button', { name: 'Create question', exact: true });
    await expect(createQuestion).toBeVisible();
    const assertBeforePreview = async () => {
      const assessmentBox = await assessment.boundingBox();
      const previewBox = await selectedScene.locator('.canvas-body').boundingBox();
      expect(assessmentBox.y + assessmentBox.height).toBeLessThanOrEqual(previewBox.y + 1);
      expect(await selectedScene.locator('.scene-context-header + .assessment-authoring-launch').count()).toBe(1);
    };
    await assertBeforePreview();
    await assessment.scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath('assessment-controls.png') });
    await createQuestion.click();
    const questionDialog = page.getByRole('dialog', { name: 'Safety knowledge check', exact: true });
    await expect(questionDialog.getByLabel('Question prompt', { exact: true })).toBeVisible();
    await questionDialog.getByRole('combobox', { name: 'Question type', exact: true }).selectOption('true-false');
    await questionDialog.getByLabel('Question prompt', { exact: true }).fill('Inspect equipment before use.');
    await questionDialog.getByRole('button', { name: 'Save question', exact: true }).click();
    await expect(questionDialog.getByText('Saved to', { exact: false })).toBeVisible();
    await questionDialog.getByRole('button', { name: 'Close question editor', exact: true }).click();
    await expect(assessment.getByRole('button', { name: 'Edit question', exact: true })).toBeVisible();
    await assertBeforePreview();
    const stageQuestion = selectedScene.locator('.visual-stage-frame .assessment-stage-region');
    await expect(stageQuestion).toHaveCount(1);
    await expect(stageQuestion).toContainText('Inspect equipment before use.');
    await page.getByRole('button', { name: 'Edit scene', exact: true }).click();
    const editor = page.getByRole('dialog').last();
    await editor.getByRole('tab', { name: 'Stage', exact: true }).click();
    await expect(editor.getByLabel('Assessment component', { exact: true })).toContainText('Inspect equipment before use.');
    const expandSections = async dialog => {
      const closed = dialog.locator('.visual-inspector details:not([open]) > summary');
      while (await closed.count()) await closed.first().click();
    };
    await expandSections(editor);
    await editor.getByRole('spinbutton', { name: 'Question x', exact: true }).fill('80');
    await editor.getByRole('spinbutton', { name: 'Question y', exact: true }).fill('160');
    await editor.getByRole('spinbutton', { name: 'Question width', exact: true }).fill('1000');
    await editor.getByRole('spinbutton', { name: 'Question height', exact: true }).fill('500');
    await editor.getByRole('button', { name: 'Save scene', exact: true }).click();
    await expect(editor).toHaveCount(0);
    const projectId = await page.evaluate(() => localStorage.getItem('chimera.activeProjectId'));
    const saved = await (await page.request.get(`/api/projects/${projectId}`)).json();
    expect(saved.storyboard.scenes[0].visualLayout.assessmentRegion).toEqual({ x: 80, y: 160, width: 1000, height: 500 });
    expect(saved.storyboard.scenes[0].assessmentItem.prompt).toBe('Inspect equipment before use.');
    await page.getByRole('button', { name: 'Edit scene', exact: true }).click();
    const reopened = page.getByRole('dialog').last();
    await expandSections(reopened);
    await expect(reopened.getByRole('spinbutton', { name: 'Question x', exact: true })).toHaveValue('80');
    await page.screenshot({ path: testInfo.outputPath('assessment-on-stage.png') });
    await reopened.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Preview course', exact: true }).click();
    const preview = page.getByRole('dialog', { name: /course preview$/ });
    await expect(preview.locator('.visual-stage-frame .assessment-stage-region')).toHaveCount(1);
    await expect(preview.locator('.assessment-stage-region')).toContainText('Inspect equipment before use.');
    await expect(preview.locator('.assessment-stage-region')).toHaveCSS('border-radius', '6px');
    expect(await preview.locator('.assessment-stage-region').evaluate(node => getComputedStyle(node).boxShadow)).toContain('5px 5px 5px');
    await expect(preview.locator('.assessment-stage-region .course-preview-assessment')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
    await preview.getByLabel('True', { exact: true }).check();
    await preview.getByRole('button', { name: 'Check answer', exact: true }).click();
    const feedbackDialog = page.getByRole('dialog', { name: 'Correct', exact: true });
    await expect(feedbackDialog).toContainText('Score 100%');
    await expect(feedbackDialog.getByRole('button', { name: 'Close feedback', exact: true })).toBeFocused();
    const feedback = feedbackDialog.locator('.assessment-feedback-message.correct');
    await expect(feedback).toHaveCSS('color', 'rgb(35, 85, 43)');
    await expect(feedback).toHaveCSS('background-color', 'rgb(231, 242, 232)');
    await page.screenshot({ path: testInfo.outputPath('assessment-feedback-modal.png') });
    await page.keyboard.press('Escape');
    await expect(feedbackDialog).toHaveCount(0);
    await expect(preview.getByRole('button', { name: 'View feedback', exact: true })).toBeFocused();
    await preview.getByRole('button', { name: 'View feedback', exact: true }).click();
    await expect(feedbackDialog).toContainText('1/2 attempts');
    await feedbackDialog.getByRole('button', { name: 'Close feedback', exact: true }).click();
    await expect(preview.locator('.assessment-stage-region')).toHaveCSS('font-size', '16px');
    await expect(preview.locator('.assessment-stage-region')).toHaveCSS('overflow-y', 'visible');
    await page.screenshot({ path: testInfo.outputPath('assessment-stage-preview.png') });
  });
}
